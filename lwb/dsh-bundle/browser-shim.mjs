import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { LWB_RUNTIME } from './runtime-config.mjs'
import { dshPackageDirectory } from './dsh-adapter/package-paths.mjs'

const SHIM_NAME = 'chromium-nosandbox.sh'

/** Single-quote a path for `sh`, including the quote itself. */
function quoted(value) {
  return `'${String(value).replaceAll("'", `'\\''`)}'`
}

/**
 * The browser this profile would launch if nobody named one: Playwright's own
 * download, resolved through the `playwright-core` that the mounted provider
 * actually depends on, so the shim and the driver can never disagree about
 * which build they mean.
 * @param runtime - DSH installation to resolve the dependency from.
 * @returns the browser binary's absolute path.
 */
export function packagedBrowser(runtime = LWB_RUNTIME.dshRuntimeDir) {
  const directory = dshPackageDirectory('playwright-core', runtime)
  const require = createRequire(join(directory, 'package.json'))
  return require(directory).chromium.executablePath()
}

function shimPath(directory) {
  return join(directory, SHIM_NAME)
}

function writeShim(target, binary) {
  const body = [
    '#!/bin/sh',
    '# Generated by the LWB bundle. Playwright MCP launches Chromium with its own',
    '# sandbox enabled, and that sandbox cannot initialise for a browser started',
    '# from a Node child process on macOS -- every page navigate ends as',
    '# "Target crashed". Adding --no-sandbox here is the one seam the mounted',
    '# provider exposes (executablePath); it forwards the rest of Playwright\'s',
    '# arguments untouched. Do not edit: rewritten on every activation.',
    `exec ${quoted(binary)} --no-sandbox "$@"`,
    '',
  ].join('\n')
  // Compare before writing: an unchanged shim does not need a new mtime on
  // every boot, so a warm start stays a read.
  if (existsSync(target) && readFileSync(target, 'utf8') === body) return target
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, body, { mode: 0o755 })
  chmodSync(target, 0o755)
  return target
}

/**
 * Which binary a work Session should drive, given that the mounted provider
 * cannot be told to disable Chromium's sandbox.
 *
 * Why this exists: `@playwright/mcp` defaults to `chromiumSandbox: true` while
 * the plain Playwright API defaults to `false`. Started from this host the
 * sandbox refuses to come up (`sandbox initialization failed: Operation not
 * permitted`), the GPU and network services fall over, the renderer takes a
 * SIGSEGV, and the MCP layer surfaces the wreckage as
 * `browserBackend.callTool: Target crashed`. Playwright's own default explains
 * why the very same browser never crashed when driven directly.
 *
 * The flag that fixes it (`--no-sandbox`) exists on the MCP server, but
 * `BrowserMcpConfig` has no field for it and the provider blanks every
 * `PLAYWRIGHT_MCP_*` variable before spawning, so neither an argument nor an
 * environment variable can reach the command line. `executablePath` can, so
 * the flag rides in on a shim.
 *
 * An explicit `LWB_BROWSER_EXECUTABLE` wins untouched: someone who names a
 * binary has already decided what to launch, and wrapping it would be this
 * module overriding that decision. A failure anywhere returns `undefined`,
 * which leaves the provider on its own default -- a browser that might crash
 * is still better than a Session that refuses to start.
 * @param options.environment - environment to read the override from.
 * @param options.runtime - DSH installation to resolve the dependency from.
 * @param options.directory - where to put the shim; defaults to pack state.
 * @param options.binary - the binary to wrap; defaults to the packaged Chromium.
 * @returns a binary for the provider, or `undefined` to leave it alone.
 */
export function resolveBrowserExecutable({ environment = process.env, runtime = LWB_RUNTIME.dshRuntimeDir, directory, binary } = {}) {
  const explicit = typeof environment.LWB_BROWSER_EXECUTABLE === 'string' ? environment.LWB_BROWSER_EXECUTABLE.trim() : ''
  if (explicit) return explicit
  // A `.cmd` cannot be exec'd the way the provider spawns it, and Windows does
  // not hit this sandbox failure in the first place.
  if (process.platform === 'win32') return undefined
  try {
    const target = shimPath(directory ?? join(LWB_RUNTIME.packStateDir, 'browser'))
    return writeShim(target, binary ?? packagedBrowser(runtime))
  } catch {
    return undefined
  }
}
